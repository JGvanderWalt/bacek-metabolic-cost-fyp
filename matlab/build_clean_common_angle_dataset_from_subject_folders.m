function [ ...
    matrixValid, ...
    matrix, ...
    message ...
] = validateAngleMatrix( ...
    angles, ...
    candidateFields, ...
    displayName, ...
    expectedGaitPoints)

    matrixValid = false;
    matrix = [];

    angleFields = ...
        fieldnames(angles);

    selectedField = '';

    for candidateIndex = 1:numel(candidateFields)

        candidateField = ...
            candidateFields{candidateIndex};

        if isfield(angles, candidateField)

            selectedField = ...
                candidateField;

            break;
        end
    end

    if isempty(selectedField)

        for candidateIndex = 1:numel(candidateFields)

            candidateField = ...
                candidateFields{candidateIndex};

            matchingIndex = find( ...
                strcmpi(angleFields, candidateField), ...
                1);

            if ~isempty(matchingIndex)

                selectedField = ...
                    angleFields{matchingIndex};

                break;
            end
        end
    end

    if isempty(selectedField)

        message = sprintf( ...
            '%s field is missing', ...
            displayName);

        return;
    end

    sourceValue = ...
        angles.(selectedField);

    if ~isnumeric(sourceValue)

        message = sprintf( ...
            '%s is not numeric', ...
            displayName);

        return;
    end

    matrix = double(sourceValue);

    if isempty(matrix)

        message = sprintf( ...
            '%s is empty', ...
            displayName);

        matrix = [];

        return;
    end

    if ndims(matrix) ~= 2

        message = sprintf( ...
            '%s is not two-dimensional', ...
            displayName);

        matrix = [];

        return;
    end

    if ...
            size(matrix, 2) ~= expectedGaitPoints && ...
            size(matrix, 1) == expectedGaitPoints

        matrix = ...
            matrix.';
    end

    if size(matrix, 2) ~= expectedGaitPoints

        message = sprintf( ...
            '%s has size %d x %d instead of cycles x %d', ...
            displayName, ...
            size(matrix, 1), ...
            size(matrix, 2), ...
            expectedGaitPoints);

        matrix = [];

        return;
    end

    if any(~isfinite(matrix(:)))

        message = sprintf( ...
            '%s contains NaN or Inf', ...
            displayName);

        matrix = [];

        return;
    end

    if size(matrix, 1) < 1

        message = sprintf( ...
            '%s contains no gait cycles', ...
            displayName);

        matrix = [];

        return;
    end

    matrixValid = true;

    message = sprintf( ...
        'Valid %d x %d', ...
        size(matrix, 1), ...
        size(matrix, 2));
end


function [ ...
    alignmentValid, ...
    angleData, ...
    message ...
] = validateCrossSetAlignment( ...
    hipValid, ...
    hipData, ...
    kneeValid, ...
    kneeData, ...
    ankleValid, ...
    ankleData, ...
    pelvisValid, ...
    pelvisData)

    alignmentValid = false;
    angleData = struct();

    if ...
            ~hipValid || ...
            ~kneeValid || ...
            ~ankleValid || ...
            ~pelvisValid

        message = ...
            'Not all four angle sets are valid';

        return;
    end

    referenceSize = ...
        size(kneeData.left);

    allSizes = [
        size(hipData.left)
        size(hipData.right)
        size(kneeData.left)
        size(kneeData.right)
        size(ankleData.left)
        size(ankleData.right)
        size(pelvisData.sagittal)
        size(pelvisData.frontal)
        size(pelvisData.transverse)
    ];

    if any( ...
            allSizes(:, 1) ~= referenceSize(1)) || ...
            any( ...
                allSizes(:, 2) ~= referenceSize(2))

        message = sprintf( ...
            ['The valid angle sets are not cycle-aligned. ' ...
             'Reference size is %d x %d.'], ...
            referenceSize(1), ...
            referenceSize(2));

        return;
    end

    angleData.hip_left = ...
        hipData.left;

    angleData.hip_right = ...
        hipData.right;

    angleData.knee_left = ...
        kneeData.left;

    angleData.knee_right = ...
        kneeData.right;

    angleData.ankle_left = ...
        ankleData.left;

    angleData.ankle_right = ...
        ankleData.right;

    angleData.pelvis_sagittal = ...
        pelvisData.sagittal;

    angleData.pelvis_frontal = ...
        pelvisData.frontal;

    angleData.pelvis_transverse = ...
        pelvisData.transverse;

    alignmentValid = true;

    message = sprintf( ...
        'All nine channels aligned: %d cycles x %d gait points', ...
        referenceSize(1), ...
        referenceSize(2));
end


function [ ...
    removeCycleMask, ...
    maximumJumpByCycle, ...
    culpritChannelByCycle, ...
    culpritFromPointByCycle, ...
    culpritValueBeforeByCycle, ...
    culpritValueAfterByCycle ...
] = detectAbnormalCycles( ...
    angleData, ...
    thresholdDegrees)

    channelNames = ...
        fieldnames(angleData);

    numberOfCycles = ...
        size(angleData.(channelNames{1}), 1);

    maximumJumpByCycle = ...
        zeros(numberOfCycles, 1);

    culpritChannelByCycle = ...
        cell(numberOfCycles, 1);

    culpritFromPointByCycle = ...
        zeros(numberOfCycles, 1);

    culpritValueBeforeByCycle = ...
        zeros(numberOfCycles, 1);

    culpritValueAfterByCycle = ...
        zeros(numberOfCycles, 1);

    for channelIndex = 1:numel(channelNames)

        channelName = ...
            channelNames{channelIndex};

        values = ...
            angleData.(channelName);

        adjacentDifferences = ...
            abs(diff(values, 1, 2));

        [ ...
            channelMaximumJump, ...
            channelMaximumPoint ...
        ] = max( ...
            adjacentDifferences, ...
            [], ...
            2);

        updateMask = ...
            channelMaximumJump > ...
            maximumJumpByCycle;

        updatedCycles = ...
            find(updateMask);

        maximumJumpByCycle(updateMask) = ...
            channelMaximumJump(updateMask);

        for updateIndex = 1:numel(updatedCycles)

            cycleNumber = ...
                updatedCycles(updateIndex);

            pointNumber = ...
                channelMaximumPoint(cycleNumber);

            culpritChannelByCycle{cycleNumber} = ...
                channelName;

            culpritFromPointByCycle(cycleNumber) = ...
                pointNumber;

            culpritValueBeforeByCycle(cycleNumber) = ...
                values(cycleNumber, pointNumber);

            culpritValueAfterByCycle(cycleNumber) = ...
                values(cycleNumber, pointNumber + 1);
        end
    end

    removeCycleMask = ...
        maximumJumpByCycle > ...
        thresholdDegrees;
end


function maximumJump = calculateMaximumAdjacentJump( ...
    angleData)

    channelNames = ...
        fieldnames(angleData);

    maximumJump = 0;

    for channelIndex = 1:numel(channelNames)

        channelName = ...
            channelNames{channelIndex};

        values = ...
            angleData.(channelName);

        currentMaximum = max( ...
            abs(diff(values, 1, 2)), ...
            [], ...
            'all');

        maximumJump = max( ...
            maximumJump, ...
            currentMaximum);
    end
end


function writeCompressedDataset( ...
    fileName, ...
    datasetPath, ...
    data)

    data = single(data);

    if isempty(data)

        error( ...
            'Cannot write an empty dataset: %s', ...
            datasetPath);
    end

    dataSize = size(data);

    if numel(dataSize) ~= 2

        error( ...
            'Dataset must be two-dimensional: %s', ...
            datasetPath);
    end

    chunkSize = [
        max(1, min(dataSize(1), 101))
        max(1, min(dataSize(2), 64))
    ].';

    h5create( ...
        fileName, ...
        datasetPath, ...
        dataSize, ...
        'Datatype', ...
        'single', ...
        'ChunkSize', ...
        chunkSize, ...
        'Deflate', ...
        6);

    h5write( ...
        fileName, ...
        datasetPath, ...
        data);
end


function writeScalarDataset( ...
    fileName, ...
    datasetPath, ...
    value)

    h5create( ...
