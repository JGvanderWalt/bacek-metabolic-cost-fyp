clear;
clc;
close all;

%% Baček dataset preparation
% Purpose: Create the aligned nine-angle-channel analysis HDF5 from the
% publicly released segmented mechanics and energetics MATLAB records.
%
% Required inputs: All subject data/SubN/Segmented/ for N = 1,...,21.
% Each folder contains SubN_segMechanics.mat and SubN_segEnergetics.mat.
%
% Output directory: Final Processed Data (created by this script).
% Outputs: HDF5, per-trial eligibility manifest, removed-cycle ledger,
% unrestricted-trial list and preparation report.
%
% Preparation: Require valid metabolic and aligned nine-channel gait
% records; reject cycles with adjacent-phase angle jumps over 10 degrees;
% retain common cycle rows; derive each trial's metabolic target from
% approximately the final fifth of its processed metabolic sequence.
%
% Usage: Place this script beside the All subject data directory and
% run it in MATLAB. The executable settings below specify all filenames.

%% 1. Settings

numberOfSubjects = 21;
numberOfTrials = 30;
expectedManifestRows = numberOfSubjects * numberOfTrials;
expectedGaitPoints = 101;

% Cycle-level waveform cleaning threshold.
adjacentJumpThresholdDegrees = 10.0;

% A trial must retain at least this many aligned cycles after cleaning.
minimumCleanCycles = 20;

scriptFolder = fileparts(mfilename('fullpath'));
subjectDataFolder = fullfile(scriptFolder, 'All subject data');
outputFolder = fullfile(scriptFolder, 'Final Processed Data');

outputHdf5File = fullfile( ...
    outputFolder, ...
    'bacek_clean_common_angles_metabolic_dataset.h5');

trialManifestFile = fullfile( ...
    outputFolder, ...
    'clean_common_angle_trial_manifest.csv');

removedCyclesFile = fullfile( ...
    outputFolder, ...
    'removed_angle_cycles.csv');

unrestrictedTrialListFile = fullfile( ...
    outputFolder, ...
    'unrestricted_common_angle_trial_list.csv');

reportFile = fullfile( ...
    outputFolder, ...
    'clean_common_angle_dataset_report.txt');

% false = stop if the clean HDF5 already exists
% true  = delete the clean outputs and rebuild them
overwriteExistingOutput = false;

% Every written dataset is read back and compared with its source.
verifyEveryStoredTrial = true;

storageTolerance = 1e-4;


%% 2. Confirm the project structure and protect existing outputs

if ~isfolder(subjectDataFolder)

    error( ...
        ['Subject-data folder not found: %s\n' ...
         'Place this script beside the All subject data folder and run it ' ...
         'from that project folder.'], ...
        subjectDataFolder);
end

if ~isfolder(outputFolder)

    mkdir(outputFolder);

    fprintf( ...
        'Created output folder: %s\n', ...
        outputFolder);
end

outputFiles = {
    outputHdf5File
    trialManifestFile
    removedCyclesFile
    unrestrictedTrialListFile
    reportFile
};

existingOutputs = ...
    outputFiles(cellfun(@isfile, outputFiles));

if ~isempty(existingOutputs)

    if overwriteExistingOutput

        for outputIndex = 1:numel(existingOutputs)

            fprintf( ...
                'Deleting existing output: %s\n', ...
                existingOutputs{outputIndex});

            delete(existingOutputs{outputIndex});
        end

    else

        error( ...
            ['One or more output files already exist in %s.\n' ...
             'Move them, rename them, or set ' ...
             'overwriteExistingOutput = true.'], ...
            outputFolder);
    end
end

fprintf('Subject-data folder found.\n');
fprintf('Outputs will be stored in: %s\n', outputFolder);


%% 3. Preallocate the complete 630-row trial manifest

manifestSubjectID = ...
    strings(expectedManifestRows, 1);

manifestSubjectNumber = ...
    zeros(expectedManifestRows, 1);

manifestTrialID = ...
    strings(expectedManifestRows, 1);

manifestTrialNumber = ...
    zeros(expectedManifestRows, 1);

manifestTrialUID = ...
    strings(expectedManifestRows, 1);

manifestMechanicsTrialPresent = ...
    false(expectedManifestRows, 1);

manifestEnergeticsTrialPresent = ...
    false(expectedManifestRows, 1);

manifestMetabolicValid = ...
    false(expectedManifestRows, 1);

manifestMetabolicMessage = ...
    strings(expectedManifestRows, 1);

manifestMetabolicSamples = ...
    NaN(expectedManifestRows, 1);

manifestMeanMetCost = ...
    NaN(expectedManifestRows, 1);

manifestHipValid = ...
    false(expectedManifestRows, 1);

manifestHipMessage = ...
    strings(expectedManifestRows, 1);

manifestKneeValid = ...
    false(expectedManifestRows, 1);

manifestKneeMessage = ...
    strings(expectedManifestRows, 1);

manifestAnkleValid = ...
    false(expectedManifestRows, 1);

manifestAnkleMessage = ...
    strings(expectedManifestRows, 1);

manifestPelvisValid = ...
    false(expectedManifestRows, 1);

manifestPelvisMessage = ...
    strings(expectedManifestRows, 1);

manifestCrossSetAlignmentValid = ...
    false(expectedManifestRows, 1);

manifestCrossSetAlignmentMessage = ...
    strings(expectedManifestRows, 1);

manifestOriginalCycles = ...
    NaN(expectedManifestRows, 1);

manifestRemovedCycles = ...
    NaN(expectedManifestRows, 1);

manifestCleanedCycles = ...
    NaN(expectedManifestRows, 1);

manifestIncludedInHdf5 = ...
    false(expectedManifestRows, 1);

manifestUnrestrictedComparisonEligible = ...
    false(expectedManifestRows, 1);

manifestMaximumOriginalJump = ...
    NaN(expectedManifestRows, 1);

manifestMaximumRemainingJump = ...
    NaN(expectedManifestRows, 1);

manifestMaximumStorageDifference = ...
    NaN(expectedManifestRows, 1);

manifestVerificationPassed = ...
    false(expectedManifestRows, 1);

manifestMechanicsFile = ...
    strings(expectedManifestRows, 1);

manifestEnergeticsFile = ...
    strings(expectedManifestRows, 1);

manifestCompilationMessage = ...
    strings(expectedManifestRows, 1);


%% 4. Prepare the removed-cycle log

removedTrialUID = strings(0, 1);
removedSubjectID = strings(0, 1);
removedTrialID = strings(0, 1);
removedTrialNumber = zeros(0, 1);
removedCondition = strings(0, 1);
removedOriginalCycleNumber = zeros(0, 1);
removedCulpritChannel = strings(0, 1);
removedFromGaitPoint = zeros(0, 1);
removedToGaitPoint = zeros(0, 1);
removedValueBefore = zeros(0, 1);
removedValueAfter = zeros(0, 1);
removedMaximumJump = zeros(0, 1);
removedReason = strings(0, 1);

removedCycleLogCount = 0;


%% 5. Compilation counters

metabolicValidCount = 0;
hipValidCount = 0;
kneeValidCount = 0;
ankleValidCount = 0;
pelvisValidCount = 0;
alignedAllAngleCount = 0;

storedTrialCount = 0;
excludedTrialCount = 0;
storedUnrestrictedTrialCount = 0;
storedBracedTrialCount = 0;

originalStoredCycleCount = 0;
removedStoredCycleCount = 0;
cleanedStoredCycleCount = 0;

fprintf('\n============================================\n');
fprintf('STARTING CLEAN COMMON-ANGLE COMPILATION\n');
fprintf('Subjects:                 %d\n', numberOfSubjects);
fprintf('Trials per subject:       %d\n', numberOfTrials);
fprintf('Expected trial rows:      %d\n', expectedManifestRows);
fprintf('Gait points per cycle:    %d\n', expectedGaitPoints);
fprintf('Jump threshold:           %.2f degrees\n', ...
    adjacentJumpThresholdDegrees);
fprintf('Minimum clean cycles:     %d\n', minimumCleanCycles);
fprintf('============================================\n\n');


%% 6. Validate, clean and compile every subject and trial

try

    for subjectNumber = 1:numberOfSubjects

        subjectCode = sprintf( ...
            'S%02d', ...
            subjectNumber);

        subjectPath = sprintf( ...
            '/subjects/%s', ...
            subjectCode);

        fprintf( ...
            'Processing %s (%d of %d)...\n', ...
            subjectCode, ...
            subjectNumber, ...
            numberOfSubjects);


        %% 6.1 Locate and load the subject files

        segmentedFolder = fullfile( ...
            subjectDataFolder, ...
            sprintf('Sub%d', subjectNumber), ...
            'Segmented');

        if ~isfolder(segmentedFolder)

            error( ...
                ['Segmented folder not found for %s:\n%s'], ...
                subjectCode, ...
                segmentedFolder);
        end

        mechanicsCandidates = {
            sprintf('Sub%d_segMechanics.mat', subjectNumber)
            sprintf('Sub%02d_segMechanics.mat', subjectNumber)
        };

        energeticsCandidates = {
            sprintf('Sub%d_segEnergetics.mat', subjectNumber)
            sprintf('Sub%02d_segEnergetics.mat', subjectNumber)
        };

        [ ...
            mechanicsFilePath, ...
            mechanicsFileName, ...
            mechanicsFound ...
        ] = findSubjectFile( ...
            segmentedFolder, ...
            mechanicsCandidates);

        [ ...
            energeticsFilePath, ...
            energeticsFileName, ...
            energeticsFound ...
        ] = findSubjectFile( ...
            segmentedFolder, ...
            energeticsCandidates);

        if ~mechanicsFound

            error( ...
                'Mechanics file not found for %s.', ...
                subjectCode);
        end

        if ~energeticsFound

            error( ...
                'Energetics file not found for %s.', ...
                subjectCode);
        end

        mechanicsLoaded = load( ...
            mechanicsFilePath, ...
            'segMechanics');

        energeticsLoaded = load( ...
            energeticsFilePath, ...
            'segEnergetics');

        if ~isfield(mechanicsLoaded, 'segMechanics')

            error( ...
                ['Variable segMechanics was not found in:\n%s'], ...
                mechanicsFilePath);
        end

        if ~isfield(energeticsLoaded, 'segEnergetics')

            error( ...
                ['Variable segEnergetics was not found in:\n%s'], ...
                energeticsFilePath);
        end

        mechanics = ...
            mechanicsLoaded.segMechanics;

        energetics = ...
            energeticsLoaded.segEnergetics;

        storedTrialsForSubject = 0;


        %% 6.2 Inspect all 30 trials

        for trialNumber = 1:numberOfTrials

            manifestRow = ...
                (subjectNumber - 1) * numberOfTrials + ...
                trialNumber;

            rawTrialField = sprintf( ...
                'T%d', ...
                trialNumber);

            storedTrialID = sprintf( ...
                'T%02d', ...
                trialNumber);

            trialUID = sprintf( ...
                '%s_%s', ...
                subjectCode, ...
                storedTrialID);

            trialPath = sprintf( ...
                '%s/trials/%s', ...
                subjectPath, ...
                storedTrialID);

            if trialNumber <= 15

                conditionName = 'unrestricted';

            else

                conditionName = 'braced';
            end

            manifestSubjectID(manifestRow) = ...
                string(subjectCode);

            manifestSubjectNumber(manifestRow) = ...
                subjectNumber;

            manifestTrialID(manifestRow) = ...
                string(storedTrialID);

            manifestTrialNumber(manifestRow) = ...
                trialNumber;

            manifestTrialUID(manifestRow) = ...
                string(trialUID);

            manifestMechanicsFile(manifestRow) = ...
                string(mechanicsFileName);

            manifestEnergeticsFile(manifestRow) = ...
                string(energeticsFileName);


            %% 6.3 Validate the metabolic target

            [ ...
                metabolicValid, ...
                validMetCost, ...
                meanMetCost, ...
                metabolicMessage, ...
                energeticsTrialPresent ...
            ] = validateMetabolicTarget( ...
                energetics, ...
                rawTrialField);

            manifestEnergeticsTrialPresent(manifestRow) = ...
                energeticsTrialPresent;

            manifestMetabolicValid(manifestRow) = ...
                metabolicValid;

            manifestMetabolicMessage(manifestRow) = ...
                string(metabolicMessage);

            if metabolicValid

                metabolicValidCount = ...
                    metabolicValidCount + 1;

                manifestMetabolicSamples(manifestRow) = ...
                    numel(validMetCost);

                manifestMeanMetCost(manifestRow) = ...
                    meanMetCost;
            end


            %% 6.4 Retrieve the mechanics trial

            if isfield(mechanics, rawTrialField)

                mechanicsTrialPresent = true;

                mechanicsTrial = ...
                    mechanics.(rawTrialField);

            else

                mechanicsTrialPresent = false;
                mechanicsTrial = struct();
            end

            manifestMechanicsTrialPresent(manifestRow) = ...
                mechanicsTrialPresent;


            %% 6.5 Validate each angle set independently

            [ ...
                hipValid, ...
                hipData, ...
                hipMessage ...
            ] = validateBilateralAngleSet( ...
                mechanicsTrial, ...
                'Hip_Left', ...
                'Hip_Right', ...
                'hip', ...
                expectedGaitPoints);

            [ ...
                kneeValid, ...
                kneeData, ...
                kneeMessage ...
            ] = validateBilateralAngleSet( ...
                mechanicsTrial, ...
                'Knee_Left', ...
                'Knee_Right', ...
                'knee', ...
                expectedGaitPoints);

            [ ...
                ankleValid, ...
                ankleData, ...
                ankleMessage ...
            ] = validateBilateralAngleSet( ...
                mechanicsTrial, ...
                'Ankle_Left', ...
                'Ankle_Right', ...
                'ankle', ...
                expectedGaitPoints);

            [ ...
                pelvisValid, ...
                pelvisData, ...
                pelvisMessage ...
            ] = validatePelvisAngleSet( ...
                mechanicsTrial, ...
                expectedGaitPoints);

            manifestHipValid(manifestRow) = ...
                hipValid;

            manifestHipMessage(manifestRow) = ...
                string(hipMessage);

            manifestKneeValid(manifestRow) = ...
                kneeValid;

            manifestKneeMessage(manifestRow) = ...
                string(kneeMessage);

            manifestAnkleValid(manifestRow) = ...
                ankleValid;

            manifestAnkleMessage(manifestRow) = ...
                string(ankleMessage);

            manifestPelvisValid(manifestRow) = ...
                pelvisValid;

            manifestPelvisMessage(manifestRow) = ...
                string(pelvisMessage);

            if hipValid
                hipValidCount = hipValidCount + 1;
            end

            if kneeValid
                kneeValidCount = kneeValidCount + 1;
            end

            if ankleValid
                ankleValidCount = ankleValidCount + 1;
            end

            if pelvisValid
                pelvisValidCount = pelvisValidCount + 1;
            end


            %% 6.6 Require a common aligned population across angle sets

            [ ...
                crossSetAlignmentValid, ...
                angleData, ...
                alignmentMessage ...
            ] = validateCrossSetAlignment( ...
                hipValid, ...
                hipData, ...
                kneeValid, ...
                kneeData, ...
                ankleValid, ...
                ankleData, ...
                pelvisValid, ...
                pelvisData);

            manifestCrossSetAlignmentValid(manifestRow) = ...
                crossSetAlignmentValid;

            manifestCrossSetAlignmentMessage(manifestRow) = ...
                string(alignmentMessage);

            if crossSetAlignmentValid

                alignedAllAngleCount = ...
                    alignedAllAngleCount + 1;

                manifestOriginalCycles(manifestRow) = ...
                    size(angleData.knee_left, 1);
            end

            includeBeforeCycleCleaning = ...
                metabolicValid && ...
                crossSetAlignmentValid;

            if ~includeBeforeCycleCleaning

                manifestIncludedInHdf5(manifestRow) = false;
                manifestVerificationPassed(manifestRow) = false;

                if ~metabolicValid && ~crossSetAlignmentValid

                    manifestCompilationMessage(manifestRow) = ...
                        "Excluded: invalid target and incomplete or unaligned angle sets";

                elseif ~metabolicValid

                    manifestCompilationMessage(manifestRow) = ...
                        "Excluded: invalid metabolic target";

                else

                    manifestCompilationMessage(manifestRow) = ...
                        "Excluded: incomplete or unaligned angle sets";
                end

                excludedTrialCount = ...
                    excludedTrialCount + 1;

                continue;
            end


            %% 6.7 Detect abnormal cycles across all nine channels

            [ ...
                removeCycleMask, ...
                maximumJumpByCycle, ...
                culpritChannelByCycle, ...
                culpritFromPointByCycle, ...
                culpritValueBeforeByCycle, ...
                culpritValueAfterByCycle ...
            ] = detectAbnormalCycles( ...
                angleData, ...
                adjacentJumpThresholdDegrees);

            keepCycleMask = ...
                ~removeCycleMask;

            originalCycleCount = ...
                size(angleData.knee_left, 1);

            removedCycleCount = ...
                sum(removeCycleMask);

            cleanedCycleCount = ...
                sum(keepCycleMask);

            manifestOriginalCycles(manifestRow) = ...
                originalCycleCount;

            manifestRemovedCycles(manifestRow) = ...
                removedCycleCount;

            manifestCleanedCycles(manifestRow) = ...
                cleanedCycleCount;

            manifestMaximumOriginalJump(manifestRow) = ...
                max(maximumJumpByCycle);

            if cleanedCycleCount < minimumCleanCycles

                manifestIncludedInHdf5(manifestRow) = false;
                manifestVerificationPassed(manifestRow) = false;

                manifestCompilationMessage(manifestRow) = sprintf( ...
                    ['Excluded: only %d clean cycles remained after ' ...
                     'waveform cleaning; at least %d were required'], ...
                    cleanedCycleCount, ...
                    minimumCleanCycles);

                excludedTrialCount = ...
                    excludedTrialCount + 1;

                continue;
            end


            %% 6.8 Record every removed cycle

            removedCycleIndices = ...
                find(removeCycleMask);

            for removedIndex = 1:numel(removedCycleIndices)

                originalCycleNumber = ...
                    removedCycleIndices(removedIndex);

                removedCycleLogCount = ...
                    removedCycleLogCount + 1;

                removedTrialUID(removedCycleLogCount, 1) = ...
                    string(trialUID);

                removedSubjectID(removedCycleLogCount, 1) = ...
                    string(subjectCode);

                removedTrialID(removedCycleLogCount, 1) = ...
                    string(storedTrialID);

                removedTrialNumber(removedCycleLogCount, 1) = ...
                    trialNumber;

                removedCondition(removedCycleLogCount, 1) = ...
                    string(conditionName);

                removedOriginalCycleNumber(removedCycleLogCount, 1) = ...
                    originalCycleNumber;

                removedCulpritChannel(removedCycleLogCount, 1) = ...
                    string( ...
                        culpritChannelByCycle{originalCycleNumber});

                removedFromGaitPoint(removedCycleLogCount, 1) = ...
                    culpritFromPointByCycle(originalCycleNumber);

                removedToGaitPoint(removedCycleLogCount, 1) = ...
                    culpritFromPointByCycle(originalCycleNumber) + 1;

                removedValueBefore(removedCycleLogCount, 1) = ...
                    culpritValueBeforeByCycle(originalCycleNumber);

                removedValueAfter(removedCycleLogCount, 1) = ...
                    culpritValueAfterByCycle(originalCycleNumber);

                removedMaximumJump(removedCycleLogCount, 1) = ...
                    maximumJumpByCycle(originalCycleNumber);

                removedReason(removedCycleLogCount, 1) = ...
                    sprintf( ...
                        ['Maximum adjacent jump across all nine angle ' ...
                         'channels exceeded %.2f degrees'], ...
                        adjacentJumpThresholdDegrees);
            end


            %% 6.9 Apply the same cycle mask to every angle channel

            angleDatasetNames = ...
                fieldnames(angleData);

            cleanedAngleData = struct();

            for angleIndex = 1:numel(angleDatasetNames)

                angleDatasetName = ...
                    angleDatasetNames{angleIndex};

                cleanedAngleData.(angleDatasetName) = ...
                    angleData.(angleDatasetName)(keepCycleMask, :);
            end

            remainingMaximumJump = ...
                calculateMaximumAdjacentJump(cleanedAngleData);

            manifestMaximumRemainingJump(manifestRow) = ...
                remainingMaximumJump;

            if remainingMaximumJump > ...
                    adjacentJumpThresholdDegrees

                error( ...
                    ['Cycle cleaning failed for %s. A jump of %.8f ' ...
                     'degrees remained.'], ...
                    trialUID, ...
                    remainingMaximumJump);
            end

            keptOriginalCycleNumbers = ...
                int32(find(keepCycleMask));


            %% 6.10 Write all nine cleaned angle datasets

            for angleIndex = 1:numel(angleDatasetNames)

                angleDatasetName = ...
                    angleDatasetNames{angleIndex};

                % MATLAB's high-level HDF5 interface reverses dimensions
                % relative to Python/h5py. Writing the transpose means
                % Python will see [clean_cycles x 101].

                writeCompressedDataset( ...
                    outputHdf5File, ...
                    [trialPath '/' angleDatasetName], ...
                    single( ...
                        cleanedAngleData.(angleDatasetName).'));
            end

            writeIntegerVectorDataset( ...
                outputHdf5File, ...
                [trialPath '/original_cycle_number'], ...
                keptOriginalCycleNumbers);

            writeCompressedDataset( ...
                outputHdf5File, ...
                [trialPath '/metcost'], ...
                single(validMetCost.'));

            writeScalarDataset( ...
                outputHdf5File, ...
                [trialPath '/metcost_mean'], ...
                single(meanMetCost));


            %% 6.11 Write trial attributes

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'subject_id', ...
                uint8(subjectNumber));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'subject_code', ...
                subjectCode);

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'trial_id', ...
                uint8(trialNumber));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'trial_uid', ...
                trialUID);

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'condition', ...
                conditionName);

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'all_angle_sets_present', ...
                uint8(1));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'number_of_angle_channels', ...
                uint8(9));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'angle_dataset_names', ...
                strjoin(angleDatasetNames, ','));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'original_cycle_count', ...
                uint16(originalCycleCount));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'removed_cycle_count', ...
                uint16(removedCycleCount));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'cleaned_cycle_count', ...
                uint16(cleanedCycleCount));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'number_of_cycles', ...
                uint16(cleanedCycleCount));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'number_of_gait_points', ...
                uint16(expectedGaitPoints));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'number_of_metabolic_samples', ...
                uint16(numel(validMetCost)));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'adjacent_jump_threshold_degrees', ...
                single(adjacentJumpThresholdDegrees));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'comparison_eligible', ...
                uint8(1));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'unrestricted_comparison_eligible', ...
                uint8(trialNumber <= 15));

            h5writeatt( ...
                outputHdf5File, ...
                trialPath, ...
                'valid', ...
                uint8(1));


            %% 6.12 Read back and verify every stored value

            if verifyEveryStoredTrial

                [ ...
                    verificationPassed, ...
                    maximumStorageDifference ...
                ] = verifyStoredTrial( ...
                    outputHdf5File, ...
                    trialPath, ...
                    cleanedAngleData, ...
                    keptOriginalCycleNumbers, ...
                    validMetCost, ...
                    meanMetCost, ...
                    storageTolerance);

                if ~verificationPassed

                    error( ...
                        'Stored-data verification failed for %s.', ...
                        trialUID);
                end

            else

                verificationPassed = true;
                maximumStorageDifference = NaN;
            end


            %% 6.13 Complete the manifest row and counters

            manifestIncludedInHdf5(manifestRow) = true;

            manifestUnrestrictedComparisonEligible(manifestRow) = ...
                trialNumber <= 15;

            manifestMaximumStorageDifference(manifestRow) = ...
                maximumStorageDifference;

            manifestVerificationPassed(manifestRow) = ...
                verificationPassed;

            manifestCompilationMessage(manifestRow) = ...
                "Stored and verified";

            storedTrialCount = ...
                storedTrialCount + 1;

            storedTrialsForSubject = ...
                storedTrialsForSubject + 1;

            originalStoredCycleCount = ...
                originalStoredCycleCount + ...
                originalCycleCount;

            removedStoredCycleCount = ...
                removedStoredCycleCount + ...
                removedCycleCount;

            cleanedStoredCycleCount = ...
                cleanedStoredCycleCount + ...
                cleanedCycleCount;

            if trialNumber <= 15

                storedUnrestrictedTrialCount = ...
                    storedUnrestrictedTrialCount + 1;

            else

                storedBracedTrialCount = ...
                    storedBracedTrialCount + 1;
            end
        end


        %% 6.14 Write subject attributes when at least one trial was stored

        if storedTrialsForSubject > 0

            h5writeatt( ...
                outputHdf5File, ...
                subjectPath, ...
                'subject_id', ...
                subjectCode);

            h5writeatt( ...
                outputHdf5File, ...
                subjectPath, ...
                'subject_number', ...
                uint8(subjectNumber));

            h5writeatt( ...
                outputHdf5File, ...
                subjectPath, ...
                'expected_trial_count', ...
                uint8(numberOfTrials));

            h5writeatt( ...
                outputHdf5File, ...
                subjectPath, ...
                'stored_common_trial_count', ...
                uint8(storedTrialsForSubject));

            h5writeatt( ...
                outputHdf5File, ...
                subjectPath, ...
                'source_mechanics_file', ...
                mechanicsFileName);

            h5writeatt( ...
                outputHdf5File, ...
                subjectPath, ...
                'source_energetics_file', ...
                energeticsFileName);

            h5writeatt( ...
                outputHdf5File, ...
                subjectPath, ...
                'cleaning_complete', ...
                uint8(1));
        end

        fprintf( ...
            '  %s complete: %d common trials stored.\n\n', ...
            subjectCode, ...
            storedTrialsForSubject);

        clear mechanicsLoaded;
        clear energeticsLoaded;
        clear mechanics;
        clear energetics;

        drawnow;
    end


    %% 6.15 Validate final counts and write root attributes

    if storedTrialCount + excludedTrialCount ~= ...
            expectedManifestRows

        error( ...
            ['Processed %d trials, but %d were expected.'], ...
            storedTrialCount + excludedTrialCount, ...
            expectedManifestRows);
    end

    if storedTrialCount == 0

        error( ...
            'No comparison-ready trials were stored.');
    end

