    h5create( ...
        fileName, ...
        datasetPath, ...
        dataSize, ...
        'Datatype', ...
        'int32', ...
        'ChunkSize', ...
        chunkSize, ...
        'Deflate', ...
        6);

    h5write( ...
        fileName, ...
        datasetPath, ...
        values);
end


function [ ...
    verificationPassed, ...
    maximumDifference ...
] = verifyStoredTrial( ...
    outputFile, ...
    trialPath, ...
    originalAngleData, ...
    originalCycleNumbers, ...
    originalMetCost, ...
    originalMeanMetCost, ...
    tolerance)

    maximumDifference = 0;

    channelNames = ...
        fieldnames(originalAngleData);

    for channelIndex = 1:numel(channelNames)

        channelName = ...
            channelNames{channelIndex};

        storedMatrix = double( ...
            h5read( ...
                outputFile, ...
                [trialPath '/' channelName]).');

        originalMatrix = ...
            originalAngleData.(channelName);

        if ~isequal( ...
                size(storedMatrix), ...
                size(originalMatrix))

            verificationPassed = false;
            maximumDifference = Inf;

            return;
        end

        currentDifference = max( ...
            abs( ...
                storedMatrix(:) - ...
                originalMatrix(:)));

        maximumDifference = max( ...
            maximumDifference, ...
            currentDifference);
    end

    storedCycleNumbers = int32( ...
        h5read( ...
            outputFile, ...
            [trialPath '/original_cycle_number']));

    storedCycleNumbers = ...
        storedCycleNumbers(:);

    originalCycleNumbers = ...
        int32(originalCycleNumbers(:));

    if ~isequal( ...
            storedCycleNumbers, ...
            originalCycleNumbers)

        verificationPassed = false;
        maximumDifference = Inf;

        return;
    end

    storedMetCost = double( ...
        h5read( ...
            outputFile, ...
            [trialPath '/metcost']));

    storedMetCost = ...
        storedMetCost(:);

    originalMetCost = ...
        originalMetCost(:);

    if numel(storedMetCost) ~= ...
            numel(originalMetCost)

        verificationPassed = false;
        maximumDifference = Inf;

        return;
    end

    maximumDifference = max([
        maximumDifference
        max( ...
            abs( ...
                storedMetCost - ...
                originalMetCost))
    ]);

    storedMeanMetCost = double( ...
        h5read( ...
            outputFile, ...
            [trialPath '/metcost_mean']));

    maximumDifference = max([
        maximumDifference
        abs( ...
            storedMeanMetCost - ...
            originalMeanMetCost)
    ]);

    verificationPassed = ...
        maximumDifference < tolerance;
end
