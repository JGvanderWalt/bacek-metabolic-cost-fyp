function [ ...
    metabolicValid, ...
    validMetCost, ...
    meanMetCost, ...
    message, ...
    trialPresent ...
] = validateMetabolicTarget( ...
    energetics, ...
    trialField)

    metabolicValid = false;
    validMetCost = [];
    meanMetCost = NaN;
    trialPresent = false;

    if ~isfield(energetics, trialField)

        message = ...
            'Energetics trial is missing';

        return;
    end

    trialPresent = true;

    trialData = ...
        energetics.(trialField);

    if ~isfield(trialData, 'Metabolic')

        message = ...
            'Metabolic structure is missing';

        return;
    end

    metabolic = ...
        trialData.Metabolic;

    if ~isfield(metabolic, 'MetCost')

        message = ...
            'MetCost field is missing';

        return;
    end

    metCost = double( ...
        metabolic.MetCost(:));

    if isfield(metabolic, 'CostTrans') && ...
            isfield(metabolic, 'RER')

        costTrans = double( ...
            metabolic.CostTrans(:));

        rer = double( ...
            metabolic.RER(:));

        scalarZeroPlaceholder = ...
            numel(metCost) == 1 && ...
            metCost == 0 && ...
            numel(costTrans) == 1 && ...
            costTrans == 0 && ...
            numel(rer) == 1 && ...
            rer == 0;

        if scalarZeroPlaceholder

            message = ...
                'Scalar-zero MetCost/CostTrans/RER placeholder';

            return;
        end
    end

    validMetCost = ...
        metCost(isfinite(metCost));

    if isempty(validMetCost)

        message = ...
            'MetCost contains no finite samples';

        return;
    end

    % Match the official Bacek MAIN_MetabolicCost.m procedure:
    % use approximately the final minute of each 5-minute test by
    % averaging from round(0.8*N) through the final MetCost sample.
    targetStartIndex = ...
        round(0.8 * length(metCost));

    targetStartIndex = ...
        max(1, targetStartIndex);

    targetMetCost = ...
        metCost(targetStartIndex:end);

    if isempty(targetMetCost) || ...
            any(~isfinite(targetMetCost))

        message = ...
            'Final MetCost target window contains invalid samples';

        validMetCost = [];
        meanMetCost = NaN;

        return;
    end

    meanMetCost = ...
        mean(targetMetCost);

    if ~isfinite(meanMetCost)

        message = ...
            'Mean final-window MetCost is not finite';

        validMetCost = [];
        meanMetCost = NaN;

        return;
    end

    if meanMetCost <= 0

        message = ...
            'Mean final-window MetCost is not positive';

        validMetCost = [];
        meanMetCost = NaN;

        return;
    end

    metabolicValid = true;

    message = sprintf( ...
        'Valid: %d finite samples; mean %.8f W/kg', ...
        numel(validMetCost), ...
        meanMetCost);
end


function [ ...
    setValid, ...
    setData, ...
    message ...
] = validateBilateralAngleSet( ...
    mechanicsTrial, ...
    leftField, ...
    rightField, ...
    setName, ...
    expectedGaitPoints)

    setValid = false;

    setData = struct( ...
        'left', ...
        [], ...
        'right', ...
        []);

    if isempty(fieldnames(mechanicsTrial))

        message = ...
            'Mechanics trial is missing';

        return;
    end

    if ~isfield(mechanicsTrial, 'Angles')

        message = ...
            'Angles structure is missing';

        return;
    end

    angles = ...
        mechanicsTrial.Angles;

    [ ...
        leftValid, ...
        leftMatrix, ...
        leftMessage ...
    ] = validateAngleMatrix( ...
        angles, ...
        {leftField}, ...
        leftField, ...
        expectedGaitPoints);

    [ ...
        rightValid, ...
        rightMatrix, ...
        rightMessage ...
    ] = validateAngleMatrix( ...
        angles, ...
        {rightField}, ...
        rightField, ...
        expectedGaitPoints);

    if ~leftValid || ~rightValid

        message = sprintf( ...
            'Invalid %s set: left [%s]; right [%s]', ...
            setName, ...
            leftMessage, ...
            rightMessage);

        return;
    end

    if ~isequal(size(leftMatrix), size(rightMatrix))

        message = sprintf( ...
            ['Invalid %s set: left/right sizes differ ' ...
             '(%d x %d versus %d x %d)'], ...
            setName, ...
            size(leftMatrix, 1), ...
            size(leftMatrix, 2), ...
            size(rightMatrix, 1), ...
            size(rightMatrix, 2));

        return;
    end

    setData.left = ...
        leftMatrix;

    setData.right = ...
        rightMatrix;

    setValid = true;

    message = sprintf( ...
        'Valid: %d cycles x %d gait points', ...
        size(leftMatrix, 1), ...
        size(leftMatrix, 2));
end


